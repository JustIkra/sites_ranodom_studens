#!/bin/bash
# Скрипт для деплоя на продакшн

echo "=== Деплой на продакшн ==="

# 1. Активировать виртуальное окружение
echo "Активация виртуального окружения..."
source venv/bin/activate

# 2. Установить зависимости для продакшена
echo "Установка зависимостей..."
pip install -r requirements_prod.txt

# 3. Применить миграции
echo "Применение миграций..."
python manage.py migrate

# 4. Собрать статические файлы
echo "Сбор статических файлов..."
python manage.py collectstatic --noinput

# 5. Проверить, что статические файлы собраны
echo "Проверка статических файлов..."
ls -la staticfiles/
ls -la staticfiles/images/

echo "=== Деплой завершен! ==="
echo "Проверьте, что все файлы загружены на хостинг"
echo "Особенно важно: папка staticfiles/ должна содержать все изображения"

